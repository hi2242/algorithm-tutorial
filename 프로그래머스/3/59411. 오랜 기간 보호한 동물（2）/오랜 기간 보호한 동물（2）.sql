-- 입양을 간 동물 중, 보호 기간이 가장 길었던 동물 두 마리의 ANIMAL_ID, NAME
-- ORDER BY 보호 기간 DESC
WITH OUTS_CTE AS (
    SELECT ANIMAL_ID
    FROM ANIMAL_OUTS
)
SELECT AI.ANIMAL_ID, AI.NAME
FROM ANIMAL_INS AS AI
INNER JOIN ANIMAL_OUTS AS AO
ON AI.ANIMAL_ID = AO.ANIMAL_ID
ORDER BY (AO.DATETIME - AI.DATETIME) DESC
LIMIT 2
;