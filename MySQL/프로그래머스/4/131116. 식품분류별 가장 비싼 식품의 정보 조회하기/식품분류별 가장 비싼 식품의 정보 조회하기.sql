-- 문제 정보
-- 식품분류별로 가격이 제일 비싼 식품의 CATEGORY, PRICE, PRODUCT_NAME
-- 식품분류가 '과자', '국', '김치', '식용유'
-- ORDER BY PRICE DESC

SELECT CATEGORY, PRICE AS MAX_PRICE, PRODUCT_NAME
FROM (
    SELECT CATEGORY, PRICE, PRODUCT_NAME, RANK() OVER(PARTITION BY CATEGORY ORDER BY PRICE DESC) AS PRICE_RANKING
    FROM FOOD_PRODUCT
) AS TEMP
WHERE PRICE_RANKING = 1
AND CATEGORY IN ('과자', '국', '김치', '식용유')
ORDER BY MAX_PRICE DESC
;