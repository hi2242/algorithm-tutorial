-- 문제 정보
-- 0시부터 23시까지 각 시간대별로 발생한 입양 건 수 조회
-- ORDER BY 시간대
WITH RECURSIVE RECURSION_CTE AS (
    SELECT 0 AS N
    UNION ALL
    SELECT N + 1
    FROM RECURSION_CTE
    WHERE N < 23
)
SELECT N AS HOUR, COALESCE(SUB.COUNT, 0) AS COUNT
FROM RECURSION_CTE AS RC
LEFT JOIN (
    SELECT HOUR(DATETIME) AS H, COUNT(*) AS COUNT
    FROM ANIMAL_OUTS
    GROUP BY HOUR(DATETIME)
) AS SUB
ON RC.N = SUB.H
ORDER BY RC.N ASC
;